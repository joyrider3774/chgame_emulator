def installed():
    """the newest installed board package's bootloaders/CHGame and its version"""
    roots = [os.path.join(os.environ.get("LOCALAPPDATA", ""), "Arduino15"), os.path.expanduser("~/.arduino15")]
    found = []
    for r in roots:
        found += glob.glob(os.path.join(r, "packages", "CHGame", "hardware", "ch32v", "*"))
    if not found:
        sys.exit("no CHGame board package installed; name a bootloaders/CHGame folder or a git tag")
    key = lambda p: [int(x) if x.isdigit() else 0 for x in os.path.basename(p).split(".")]
    newest = max(found, key=key)
    return os.path.join(newest, "bootloaders", "CHGame"), os.path.basename(newest)


def read(source, name):
    if source.startswith("v") and not os.path.isdir(source):
        return subprocess.run(["git", "-C", os.path.join(GITHUB, "CHGame"), "show", "%s:%s/%s" % (source, SUB, name)],
                              check=True, capture_output=True).stdout
    with open(os.path.join(source, name), "rb") as f:
        return f.read()


def main():
    if len(sys.argv) > 1:
        source = sys.argv[1]
        version = source[1:] if source.startswith("v") and not os.path.isdir(source) else "the given folder's"
    else:
        source, version = installed()
    images = [(name, read(source, f), f) for name, f in BOARDS]
    out = ["/*",
           " * The CHGame bootloader for each board the emulator emulates, as the CHGame",
           " * board package (%s) ships it in bootloaders/CHGame: the \"USB Only\"" % version,
           " * bootloader (Tools > Bootloader; built from platform/bootloader in",
           " * github.com/bateske/CHGame with `build.sh nomenu --board=<board>`) that",
           " * sits in the first 12 KB of a CHGame's flash. On reset it checks the",
           " * application's metadata page (0xF700: magic, version, length, CRC-32) and",
           " * jumps to the application at 0x3000, or stays in its USB update mode when",
           " * the application asked for that or none is installed. Each board's is",
           " * built for its pins, and a later board's carries its target id at 0x14.",
           " * src/board.c says which is which. The menu bootloaders are in bootloaders/",
           " * (tools/build_bootloaders.sh) for --bootloader.",
           " *",
           " * Generated by tools/make_bootloader_image.py from:",
           ]
    for name, data, f in images:
        out.append(" *   %-5s %s (%d bytes)" % (name, f, len(data)))
    out += [" * Do not edit.", " *", LICENCE, " */", "#include <stdint.h>", "#include <stddef.h>", ""]
    for name, data, f in images:
        out.append("const uint8_t chg_bootloader_%s[] = {" % name)
        for i in range(0, len(data), 16):
            out.append("    " + " ".join("0x%02x," % b for b in data[i:i + 16]))
        out.append("};")
        out.append("const size_t chg_bootloader_%s_size = sizeof(chg_bootloader_%s);" % (name, name))
        out.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s: %s" % (OUT, ", ".join("%s %d B" % (n, len(d)) for n, d, _ in images)))


if __name__ == "__main__":
    main()
