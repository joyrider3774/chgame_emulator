"""Writes src/bootloader_image.c: the bootloader the emulator puts at 0x0000
for each board it emulates, from the CHGame board package's own files.

    python tools/make_bootloader_image.py [boards]

boards: a board package's bootloaders/CHGame folder (the installed package's
by default: ~/AppData/Local/Arduino15 or ~/.arduino15), or a git tag of the
c:/github/CHGame clone (v0.4.0), whose platform/board/arduino/CHGame/
bootloaders/CHGame it then reads.

Each board's "USB Only" bootloader, chgame_boot_nomenu.bin: rev0's at the
top of that folder, a later board's in its own subfolder (rev1/). A new board
is a line in BOARDS here and one in src/board.c.
"""
